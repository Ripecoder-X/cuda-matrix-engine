#!/usr/bin/env bash
set -u

have() {
    command -v "$1" >/dev/null 2>&1
}

section() {
    printf '\n## %s\n\n' "$1"
}

run_cmd() {
    local display="$1"
    shift
    printf '```\n$ %s\n' "$display"
    if have "$1"; then
        "$@" 2>&1 || true
    else
        printf 'NOT FOUND\n'
    fi
    printf '```\n'
}

printf '# Environment\n\n'
printf 'Generated by scripts/environment.sh on %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"

section 'Operating system'
run_cmd 'uname -a' uname -a
run_cmd 'cat /etc/os-release' cat /etc/os-release

section 'CPU and memory'
run_cmd 'lscpu' lscpu
run_cmd 'free -g' free -g

section 'GPU'
run_cmd 'nvidia-smi --query-gpu=name,driver_version,memory.total,compute_cap --format=csv' \
    nvidia-smi --query-gpu=name,driver_version,memory.total,compute_cap --format=csv

section 'Driver vs toolkit (separate values)'
run_cmd 'nvidia-smi --query-gpu=driver_version --format=csv,noheader' \
    nvidia-smi --query-gpu=driver_version --format=csv,noheader
run_cmd 'nvcc --version' nvcc --version

section 'Other tools'
run_cmd 'cmake --version' cmake --version
run_cmd 'g++ --version' g++ --version
run_cmd 'ncu --version' ncu --version
run_cmd 'nsys --version' nsys --version
run_cmd 'python3 --version' python3 --version

SANITIZER="${CME_COMPUTE_SANITIZER:-}"
if [[ -z "${SANITIZER}" && -x /tmp/cuda-sanitizer-13-2/usr/local/cuda-13.2/bin/compute-sanitizer ]]; then
    SANITIZER=/tmp/cuda-sanitizer-13-2/usr/local/cuda-13.2/bin/compute-sanitizer
fi
if [[ -z "${SANITIZER}" ]] && command -v compute-sanitizer >/dev/null 2>&1; then
    SANITIZER="$(command -v compute-sanitizer)"
fi
printf '```\n$ compute-sanitizer --version\n'
if [[ -n "${SANITIZER}" && -x "${SANITIZER}" ]]; then
    "${SANITIZER}" --version 2>&1 || true
else
    printf 'NOT FOUND\n'
fi
printf '```\n'

section 'Nominal GPU state at recording time'
run_cmd 'nvidia-smi --query-gpu=clocks.sm,temperature.gpu,power.draw --format=csv,noheader,nounits' \
    nvidia-smi --query-gpu=clocks.sm,temperature.gpu,power.draw --format=csv,noheader,nounits

section 'Windows 11 secondary environment'
printf 'NOT AVAILABLE. Not tested by this script.\n'
